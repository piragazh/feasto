export const CREDIT_SITES = CALL_SITES.filter((s) => !s.noCredits);

export function summarise(sites = CREDIT_SITES) {
  const sources = new Set(sites.map((s) => s.source));
  const byEndpoint = {};
  for (const s of sites) byEndpoint[s.endpoint] = (byEndpoint[s.endpoint] || 0) + 1;
  return {
    callSites: sites.length,
    sources: sources.size,
    highVolume: sites.filter((s) => s.volume === 'High').length,
    byEndpoint,
  };
}