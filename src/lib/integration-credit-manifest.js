// Static inventory of every place this app calls a Base44 Core integration.
//
// WHY THIS FILE EXISTS
// Integration credits are spent at call time, per integration call, and the app
// itself has no meter for them: nothing in the database records "this function
// spent 3 credits". What the app CAN know for certain is where the calls are
// written, which integration each one uses and how often it fires. That is what
// this file holds — an honest, code-derived inventory.
//
// Figures here are CALL-SITE ESTIMATES, never billed amounts. Where a real
// runtime counter exists (AiUsageDay for AI replies, AiGenerationLog for AI
// pictures, MessageJob for emails sent) the entry carries a `measuredKey` and
// the page shows the measured number next to the estimate.
//
// Only Base44 Core integrations consume Base44 integration credits:
//   InvokeLLM, SendEmail, GenerateImage, GenerateSpeech, GenerateVideo,
//   TranscribeAudio, ExtractDataFromUploadedFile.
// Everything the app talks to with its own keys — Stripe, Twilio, HTTPSMS,
// Retell, Uber Eats, OpenWeatherMap — is billed by that provider directly and
// costs no Base44 credits. File uploads are storage, also not integration
// credits. Both are called out on the page so the list is not misleading.

